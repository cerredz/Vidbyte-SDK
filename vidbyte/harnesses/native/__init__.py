"""FILE: vidbyte/harnesses/native/__init__.py

PURPOSE: The package of harness thread functions: nine async functions that run, continue and fork Grok Build, opencode and Muse Code threads by driving each vendor's installed command-line tool headless once, with the caller's API key, and return the thread id and the final answer.
ROLE IN CODEBASE: The public entry point of vidbyte.harnesses.native. It re-exports the three functions of each harness subpackage (grok, opencode, muse), the records a caller builds or receives (GrokThreadConfig, OpencodeThreadConfig, MuseThreadConfig, NativeThreadResult), the one error type (NativeThreadError) and the config enums. Nothing here is re-exported from vidbyte or vidbyte.harnesses, and `import vidbyte` never imports this package.
ARCHITECTURE NOTE: A package initializer that only imports and re-exports. The functions live in each harness's threads module, the records in vidbyte/lib/dataclasses/native_threads.py, the enums in vidbyte/lib/enums/native_threads.py and the error in vidbyte/lib/errors/base.py; the shared plumbing lives in the hostkit subpackage, which is internal.
FUNCTION INVENTORY: No functions of its own. run_grok_thread, continue_grok_thread, fork_grok_thread, run_opencode_thread, continue_opencode_thread, fork_opencode_thread, run_muse_thread, continue_muse_thread and fork_muse_thread come from the harness subpackages.
COMMON MODIFICATION PATTERNS: A new harness adds its own subpackage with three functions and one config record, and this module re-exports them in the literal __all__.
WHAT NOT TO DO IN THIS FILE: 1. Do not add import-time side effects such as finding an executable or reading a key. 2. Do not export the flow classes, codecs, launchers or hostkit helpers; they are internal plumbing.
KNOWN EDGE CASES: None; the module only re-exports names.
RELATED DOCS: vidbyte/harnesses/README.md
TESTS: tests/features/harness_threads/
"""

