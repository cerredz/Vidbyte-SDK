"""FILE: vidbyte/harnesses/native/__init__.py

PURPOSE: The package of native coding-harness code, in two shapes. The codex subpackage is the Codex host: one host class that wraps the official openai-codex SDK in small, atomic functions. The grok, opencode and muse subpackages hold the harness thread functions: 65 async functions that drive each vendor's installed command-line tool (Grok Build, opencode, Muse Code) headless. Nine run, continue and fork a thread once with the caller's API key and return the thread id and the final answer; nine browser functions (run_<harness>_with_browser, continue_<harness>_with_browser, fork_<harness>_with_browser) do the same with the caller's browser tools mounted for that one call and also return the calls made on those tools and the files they saved; 22 keyless helpers list, get, read, follow, search and delete the threads a vendor keeps, and init_muse_workspace sets Muse up; 24 command and skill functions run one bundled command, agent or skill with the caller's key and return only when the run's own record shows it ran.
ROLE IN CODEBASE: The public entry point of the harness thread functions. It re-exports every function of each thread subpackage (grok, opencode, muse), the records a caller builds or receives (GrokThreadConfig, OpencodeThreadConfig, MuseThreadConfig, NativeThreadResult, NativeThreadSummary, NativeCommandOutput, BrowserThreadResult, BrowserToolCall), the one error type (NativeThreadError) and the enums a caller passes (the config enums, GrokThreadScope and GrokCommand). It does not re-export the Codex host: callers import CodexHost and the Codex module functions from vidbyte.harnesses.native.codex. The root vidbyte package re-exports every name here, the functions lazily, so `import vidbyte` never imports this package; nothing here is re-exported from vidbyte.harnesses.
ARCHITECTURE NOTE: A package initializer that only imports and re-exports. The thread functions live in each harness's threads module, the helpers in its helpers module, the command and skill functions in its commands module and the browser functions in its browser module; the records live in vidbyte/lib/dataclasses/native_threads.py and browser_tools.py, the enums in vidbyte/lib/enums/native_threads.py and the error in vidbyte/lib/errors/base.py; the shared plumbing lives in the hostkit subpackage, which is internal. Nothing here imports a vendor SDK, so importing this package never requires an optional extra; the codex subpackage loads openai-codex only when a host opens.
FUNCTION INVENTORY: No functions of its own. From grok: run_grok_thread, continue_grok_thread and fork_grok_thread; the browser functions run_grok_with_browser, continue_grok_with_browser and fork_grok_with_browser; the helpers list_grok_threads, list_recent_grok_threads, list_grok_threads_since, get_grok_thread, read_grok_thread, get_grok_thread_lineage, search_grok_threads and delete_grok_thread; the commands run_grok_command, run_grok_goal, run_grok_implement, run_grok_design, run_grok_execute_plan, run_grok_review, run_grok_code_review, run_grok_resume_claude, run_grok_resume_codex, run_grok_resume_cursor, run_grok_imagine, run_grok_imagine_video, run_grok_plan and run_grok_explore. From opencode: run_opencode_thread, continue_opencode_thread and fork_opencode_thread; run_opencode_with_browser, continue_opencode_with_browser and fork_opencode_with_browser; the same eight helpers with opencode in the name; run_opencode_command, run_opencode_review, run_opencode_init and run_opencode_plan. From muse: run_muse_thread, continue_muse_thread and fork_muse_thread; run_muse_with_browser, continue_muse_with_browser and fork_muse_with_browser; list_muse_threads, list_recent_muse_threads, list_muse_threads_since, get_muse_thread, read_muse_thread, get_muse_thread_lineage and init_muse_workspace; run_muse_skill, run_muse_goal, run_muse_plan, run_muse_import, run_muse_scaffold and run_muse_browser_app.
COMMON MODIFICATION PATTERNS: A new thread harness adds its own subpackage with three thread functions, three browser functions and one config record, and this module re-exports them in the literal __all__; a new function of an existing harness is bound in its subpackage and listed here too. A new host harness adds its own subpackage beside codex, and this module leaves it unexported.
WHAT NOT TO DO IN THIS FILE: 1. Do not add import-time side effects such as finding an executable or reading a key. 2. Do not export the flow classes, codecs, launchers, mount compilers, browser harnesses or hostkit helpers; they are internal plumbing. 3. Do not import the codex subpackage or any vendor SDK here.
KNOWN EDGE CASES: None; the module only re-exports names.
RELATED DOCS: vidbyte/harnesses/README.md
TESTS: tests/features/harness_threads/ for the re-exports; tests/features/codex_host/ for the codex subpackage.
"""

