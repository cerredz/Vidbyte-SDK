"""Context Protocol Header

Description:
    Exports the root Vidbyte SDK client and top-level public tool, agent, context,
    paradigm, pipeline, ledger-driven multi-agent, and validated workflow contracts.
Purpose:
    Keeps common SDK imports concise while leaving specialized built-in tools in
    their category packages.
Architecture:
    - VidbyteSDK: Root namespace client.
    - Agent exports: BaseAgent, AgentCard, AgentMessage, AgentRegistry, AgentRunnerConfig, AgentSpec.
    - Tool exports: BaseTool, ToolCall, ToolExecutor, ToolParameter, ToolPermission, ToolRegistry, ToolResult, ToolSpec, ToolStatus, ToolsFormatter.
    - MCP exports: McpServerConfig, McpServerHandle, McpToolPermission.
    - Context exports: context contracts plus general problem-solving challenge records.
    - Preset exports: BudgetPreset, PermissionPreset.
    - Pipeline exports: BasePipeline, ConditionalPipeline, ParallelPipeline, PipelineNode, SequentialPipeline.
    - Multi-agent exports: MultiAgent, MagenticOneOrchestrator, TaskLedger, AgentBinding, AgentTransfer, and immutable ledger contracts.
    - Workflow exports: StateGraph, StateMachine, stages, validators, routers, policies, records, and typed errors.
    - Error exports: MCP, pipeline, workflow, multi-agent execution, task-ledger, and agent-transfer error families.
Key Functions / Exports:
    - VidbyteSDK: Main SDK entry point.
    - BaseAgent: Base class for building agents.
    - BaseTool: Base class for building tools.
    - BaseContext: Base class for managing conversation contexts.
Relation to codebase as a whole:
    Acts as the primary public API entry point of the entire SDK, unifying all sub-packages (agents, context, tools, mcp, pipelines, middleware) into a single export surface for consumers.
Similar files:
    - vidbyte/context/__init__.py: Exposes public context management namespace.
    - vidbyte/agents/__init__.py: Exposes agent contracts.
    - vidbyte/tools/__init__.py: Exposes tool abstractions.
"""

